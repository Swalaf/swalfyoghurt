    public const PRIVACY = <<<'MD'
# Privacy Policy

{company} ({address}) runs {brand} at {domain} and is responsible for your personal data.

## What we collect
- **Account details:** name, email address, password (stored hashed), and your settings.
- **Your projects:** descriptions, files, chat messages with the AI and published apps.
- **Billing:** plan, payment amounts and references. Card details are handled by our payment providers (Stripe or Paystack) and never reach our servers.
- **Technical data:** IP address and activity logs used for security and troubleshooting.

## Why we use it
To run the service you signed up for (contract), to keep it secure and prevent abuse (legitimate interest), to take payments and keep accounting records (legal obligation), and to email you about your account.

## Who we share it with
- **AI providers** that generate code: the text of your requests and the relevant project files are sent to them to produce answers.
- **Payment providers** to process payments.
- **Email and hosting providers** that run the service for us.

We don't sell your data.

## Cookies
We only use cookies that are needed for the site to work (your sign-in session and security tokens). We don't use advertising or tracking cookies.

## How long we keep it
While your account exists. When you delete your account we delete your profile and projects; we keep payment records as long as tax law requires.

## Your rights
You can download a copy of your data and delete your account at any time from Account & security. Depending on where you live you may also have the right to correct, restrict or object to processing, and to complain to your data protection authority. Contact us at {email}.

## International transfers
Our providers may process data in other countries. Where required, we rely on appropriate safeguards such as standard contractual clauses.

_Last updated {date}._
MD;
}
