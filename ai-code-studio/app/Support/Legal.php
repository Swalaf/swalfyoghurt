<?php

namespace App\Support;

use Illuminate\Support\Str;

/**
 * Default Terms / Privacy templates. Admins edit them under Admin → Settings → Legal.
 * They are starting points, not legal advice — have them reviewed for your jurisdiction.
 */
class Legal
{
    public static function render(string $doc): string
    {
        $text = (string) (Settings::get('legal_'.$doc) ?: self::template($doc));
        $text = strtr($text, [
            '{company}' => (string) Settings::get('company_name'),
            '{brand}' => Settings::brand(),
            '{email}' => (string) (Settings::get('support_email') ?: 'the support address on our website'),
            '{address}' => (string) (Settings::get('legal_address') ?: '—'),
            '{domain}' => (string) (Settings::get('brand_domain') ?: request()->getHost()),
            '{date}' => now()->toFormattedDateString(),
        ]);

        return Str::markdown($text, ['html_input' => 'escape', 'allow_unsafe_links' => false]);
    }

    public static function template(string $doc): string
    {
        return $doc === 'privacy' ? self::PRIVACY : self::TERMS;
    }

    public const TERMS = <<<'MD'
